import { appMachine } from './appMachine.js';
import { authMachine } from './authMachine.js';
import { toMermaid } from './createMachine.js';
import { gameMachine } from './gameMachine.js';
import { playerMachine } from './playerMachine.js';
import { setupMachine } from './setupMachine.js';

/** Every explicit state machine in the app, in reading order. */
export const MACHINES = [
  { machine: appMachine, file: 'src/machines/appMachine.js', usedBy: 'src/App.jsx' },
  { machine: authMachine, file: 'src/machines/authMachine.js', usedBy: 'src/components/AuthGate.jsx' },
  { machine: setupMachine, file: 'src/machines/setupMachine.js', usedBy: 'src/hooks/useSetup.js' },
  {
    machine: gameMachine,
    file: 'src/machines/gameMachine.js',
    usedBy: 'src/hooks/useLocalGame.js (useReducer), src/game/session.js (Firebase transactions)',
  },
  { machine: playerMachine, file: 'src/machines/playerMachine.js', usedBy: 'src/components/game/SongPlayer.jsx' },
];

const escapeCell = (text = '') => text.replaceAll('|', '\\|');
const code = (text) => '`' + text + '`';

function renderMachine({ machine, file, usedBy }) {
  const states = Object.entries(machine.definition.states);
  return [
    `## \`${machine.id}\``,
    '',
    `Defined in ${code(file)} · used by ${usedBy.split(', ').map(code).join(', ')}`,
    '',
    '```mermaid',
    toMermaid(machine),
    '```',
    '',
    '| State | Description | Events |',
    '| --- | --- | --- |',
    ...states.map(
      ([name, node]) =>
        `| ${code(name)} | ${escapeCell(node.description)} | ${machine.events(name).map(code).join(', ') || '— (final)'} |`,
    ),
    '',
  ].join('\n');
}

/** Markdown for docs/state-machines.md. Regenerate with `npm run docs:machines`. */
export function renderMachineDocs() {
  return [
    '# State machines',
    '',
    '<!-- Generated by `npm run docs:machines` from src/machines/*. Do not edit by hand. -->',
    '',
    'Every piece of non-trivial UI/game state is an explicit, pure state machine built',
    'with `createMachine` (`src/machines/createMachine.js`). Machines are plain data +',
    'pure functions: React runs them with `useReducer`, Firebase runs the game machine',
    'inside transactions, and tests call `machine.transition(state, event)` directly.',
    'Events a state does not accept are ignored (the same state object is returned),',
    'so double clicks and stale network events are harmless.',
    '',
    ...MACHINES.map(renderMachine),
  ].join('\n');
}
